#[test]
fn dispute_split_and_cancel() {
    let s = setup();
    let id = s.escrow.create_contract(
        &s.client,
        &s.freelancer,
        &s.token.address,
        &vec![&s.env, 400i128],
    );
    s.escrow.deposit_funds(&id, &400);
    s.escrow.open_dispute(&id, &s.freelancer);
    s.escrow.resolve_dispute(&id, &2_500);
    assert_eq!(s.token.balance(&s.freelancer), 100);
    assert_eq!(s.token.balance(&s.client), 900);

    let id2 = s.escrow.create_contract(
        &s.client,
        &s.freelancer,
        &s.token.address,
        &vec![&s.env, 50i128],
    );
    s.escrow.deposit_funds(&id2, &50);
    s.escrow.cancel_contract(&id2);
    assert_eq!(s.token.balance(&s.client), 900);
    assert_eq!(
        s.escrow.get_contract(&id2).status,
        ContractStatus::Cancelled
    );
}

/// Reference `floor(held * bps / 10_000)` computed in 256-bit precision.
///
/// `held * bps` needs up to 142 bits, so it cannot be formed in `i128` or even
/// `u128`. It is carried as two `u128` halves instead: `held` is split into
/// `a * 2^64 + b`, the product into `hi * 2^64 + lo`, and the quotient is
/// assembled with long division.
///
/// Every intermediate is in range: `a, b < 2^64` and `bps < 2^14`, so
/// `hi, lo < 2^78`; `r1 < 10^4`, so `r1 * 2^64 + lo < 2^79`. The final
/// `q1 * 2^64 + q2` equals `floor(held * bps / D)`, which is at most `held`
/// because `bps <= D`, so it fits back into `i128`.
fn reference_split(held: i128, bps: u32) -> i128 {
    const D: u128 = 10_000;
    let held = held as u128;
    let bps = bps as u128;

    let a = held >> 64;
    let b = held & ((1u128 << 64) - 1);

    let hi = a * bps;
    let lo = b * bps;

    let q1 = hi / D;
    let r1 = hi % D;
    let rem = r1 * (1u128 << 64) + lo;
    let q2 = rem / D;

    (q1 * (1u128 << 64) + q2) as i128
}

/// Deterministic `(held, bps)` pairs: the interesting small values, the exact
/// points where the old formula crossed `i128::MAX / 10_000`, and values at the
/// top of the range. Generated by index so the list is identical on every run
/// and on every platform.
///
/// `std::vec::Vec`, not the `soroban_sdk::Vec` that `use super::*` brings in:
/// this is host-side test scaffolding, not contract storage.
fn split_cases() -> std::vec::Vec<(i128, u32)> {
    let mut cases: std::vec::Vec<(i128, u32)> = std::vec::Vec::new();

    // Hand-picked boundaries and edge values.
    let boundaries: [i128; 12] = [
        0,
        1,
        2,
        9_999,
        10_000,
        10_001,
        i128::MAX / 10_000 - 1,
        i128::MAX / 10_000,
        i128::MAX / 10_000 + 1,
        i128::MAX / 4,
        i128::MAX / 2,
        i128::MAX,
    ];
    for held in boundaries {
        for bps in [0u32, 1, 2_500, 9_999, 10_000] {
            cases.push((held, bps));
        }
    }

    // A deterministic sweep, so the comparison covers many magnitudes and every
    // remainder class modulo 10_000.
    let mut held: i128 = 1;
    for i in 0..120u32 {
        cases.push((held, (i * 97) % 10_001));
        cases.push((held, 10_000 - (i % 7)));
        // Multiply by an odd-ish factor to walk magnitudes without repeating.
        held = held.saturating_mul(3).saturating_add(7);
        if held > i128::MAX / 4 {
            held = 1 + (i as i128) * 7919;
        }
    }

    cases
}

/// The whole point of the new formula: it must agree with exact 256-bit
/// arithmetic for every input, including the ones that used to trap.
#[test]
fn split_by_bps_matches_a_256_bit_reference() {
    let cases = split_cases();
    assert!(
        cases.len() >= 100,
        "expected at least 100 cases, got {}",
        cases.len()
    );

    for (held, bps) in cases {
        let got = split_by_bps(held, bps);
        let want = reference_split(held, bps);
        assert_eq!(got, want, "split_by_bps({held}, {bps})");
    }
}

/// The split must conserve value exactly and never hand out more than was held.
#[test]
fn split_conserves_value_and_stays_in_range() {
    for (held, bps) in split_cases() {
        let to_freelancer = split_by_bps(held, bps);
        assert!(to_freelancer >= 0, "negative payout for ({held}, {bps})");
        assert!(
            to_freelancer <= held,
            "payout exceeded held for ({held}, {bps})"
        );
        // `held - to_freelancer` is what `resolve_dispute` sends to the client.
        let to_client = held - to_freelancer;
        assert_eq!(
            to_freelancer + to_client,
            held,
            "value not conserved for ({held}, {bps})"
        );
    }
}

/// The boundary the old implementation crossed. Below it the naive product fits,
/// above it it does not — the formula must be correct on both sides.
#[test]
fn split_is_exact_on_both_sides_of_the_old_overflow_threshold() {
    let threshold = i128::MAX / BPS_DENOMINATOR;

    // At the threshold the old form still fits, and must agree with the new one.
    for held in [threshold - 1, threshold, threshold + 1] {
        for bps in [1u32, 2_500, 9_999, 10_000] {
            assert_eq!(split_by_bps(held, bps), reference_split(held, bps));
        }
    }

    // Above it the old form would panic; the new one returns the exact value.
    let held = i128::MAX / 2;
    assert_eq!(split_by_bps(held, 10_000), held);
    assert_eq!(split_by_bps(held, 0), 0);
    assert_eq!(split_by_bps(held, 5_000), held / 2);
    assert_eq!(split_by_bps(held, 2_500), held / 4);
}

/// `total_rating` is a `u32` and a rating is 1..=5, so the counter can be pushed
/// over the ceiling. It used to abort with a host panic; it must now return a
/// typed error the caller can surface.
#[test]
fn issue_reputation_reports_overflow_instead_of_panicking() {
    let s = setup();
    let id = s.escrow.create_contract(
        &s.client,
        &s.freelancer,
        &s.token.address,
        &vec![&s.env, 100i128],
    );
    s.escrow.deposit_funds(&id, &100);
    s.escrow.release_milestone(&id, &0);
    assert_eq!(s.escrow.get_contract(&id).status, ContractStatus::Completed);

    // Seed the freelancer's reputation at one below the ceiling. `u32::MAX - 1`
    // plus any valid rating overflows; `u32::MAX - 5` is the largest value that
    // still fits the maximum rating of 5.
    let key = DataKey::Reputation(s.freelancer.clone());
    s.env.as_contract(&s.escrow.address, || {
        s.env.storage().persistent().set(
            &key,
            &Reputation {
                completed_contracts: 1,
                total_rating: u32::MAX - 1,
            },
        );
    });

    assert_eq!(
        s.escrow.try_issue_reputation(&id, &5),
        Err(Ok(EscrowError::ArithmeticOverflow))
    );

    // The contract must not have been marked as rated, so the call can be
    // retried once the counter is in range again.
    assert!(!s.escrow.get_contract(&id).reputation_issued);

    // A rating that does fit still succeeds.
    s.env.as_contract(&s.escrow.address, || {
        s.env.storage().persistent().set(
            &key,
            &Reputation {
                completed_contracts: 1,
                total_rating: u32::MAX - 5,
            },
        );
    });
    s.escrow.issue_reputation(&id, &5);
    let rep = s.escrow.get_reputation(&s.freelancer);
    assert_eq!(rep.total_rating, u32::MAX);
    assert_eq!(rep.completed_contracts, 2);
}

