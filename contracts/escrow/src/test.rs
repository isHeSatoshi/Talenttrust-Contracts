/// The regression this branch exists for.
///
/// `resolve_dispute` used to compute `held * freelancer_bps as i128 / 10_000`,
/// which overflows for any `held` above `i128::MAX / 10_000`. The release
/// profile sets `overflow-checks = true`, so the call panicked and the escrow
/// was stuck in `Disputed` forever: no other entry point moves funds out of
/// that state.
///
/// `i128::MAX / 2` is far past that threshold, so on `main` this test panics
/// instead of returning.
#[test]
fn resolve_dispute_survives_a_held_balance_near_i128_max() {
    let s = setup();
    let held: i128 = i128::MAX / 2;
    StellarAssetClient::new(&s.env, &s.token.address).mint(&s.client, &held);

    let id = s.escrow.create_contract(
        &s.client,
        &s.freelancer,
        &s.token.address,
        &vec![&s.env, held],
    );
    s.escrow.deposit_funds(&id, &held);
    s.escrow.open_dispute(&id, &s.freelancer);

    // Measured as a delta, so the balance `setup()` already minted to the client
    // is not part of the expectation.
    let client_before = s.token.balance(&s.client);
    s.escrow.resolve_dispute(&id, &2_500);

    // floor(held * 2500 / 10_000) == floor(held / 4), and the split conserves value.
    let to_freelancer = held / 4;
    let to_client = held - to_freelancer;
    assert_eq!(s.token.balance(&s.freelancer), to_freelancer);
    assert_eq!(s.token.balance(&s.client), client_before + to_client);
    assert_eq!(to_freelancer + to_client, held);

    let c = s.escrow.get_contract(&id);
    assert_eq!(c.status, ContractStatus::Resolved);
    assert_eq!(c.funded_amount, to_freelancer);
    assert_eq!(c.released_amount, to_freelancer);
}
